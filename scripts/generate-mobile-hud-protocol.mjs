import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const protocolPath = join(root, 'schemas', 'mobile-hud', 'protocol.json')
const privacyPath = join(root, 'schemas', 'hud-core', 'privacy-denylist.json')
const tsPath = join(root, 'src', 'protocol', 'mobileHud.generated.ts')
const kotlinPath = join(root, 'apps', 'android', 'app', 'src', 'main', 'java', 'com', 'claudehud', 'one', 'mobile', 'MobileHudProtocol.kt')
const swiftPath = join(root, 'schemas', 'mobile-hud', 'generated', 'MobileHudProtocol.swift')

const mode = process.argv.includes('--check') ? 'check' : 'write'
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'))
const protocol = readJson(protocolPath)
const privacy = readJson(privacyPath)
const header = 'AUTO-GENERATED by scripts/generate-mobile-hud-protocol.mjs. Do not edit manually.'

const json = (value) => JSON.stringify(value, null, 2)
const quotedList = (values, indent = '  ') => values.map((value) => `${indent}${JSON.stringify(value)}`).join(',\n')
const kotlinStringList = (values, indent = '        ') => values.map((value) => `${indent}${JSON.stringify(value)}`).join(',\n')
const swiftStringList = (values, indent = '        ') => values.map((value) => `${indent}${JSON.stringify(value)}`).join(',\n')

const outputs = new Map()

outputs.set(tsPath, `// ${header}

export const MOBILE_HUD_PROTOCOL = ${json({
  protocolVersion: protocol.protocolVersion,
  schemaVersion: protocol.schemaVersion,
  trustedViewPrivacyLevel: protocol.privacy.trustedViewPrivacyLevel,
  notificationSensitivity: protocol.privacy.notificationSensitivity,
  mobileExecutionRole: protocol.privacy.mobileExecutionRole,
  rawTranscriptPolicy: protocol.privacy.rawTranscriptPolicy,
  rawToolDataPolicy: protocol.privacy.rawToolDataPolicy,
  terminalJump: protocol.displayPolicy.terminalJump,
  approvalActions: protocol.displayPolicy.approvalActions,
  questionActions: protocol.displayPolicy.questionActions,
  transport: protocol.security.transport,
  deviceIdentity: protocol.security.deviceIdentity,
  intentAuth: protocol.security.intentAuth,
  deviceIdIsCredential: protocol.security.deviceIdIsCredential,
})} as const

export const MOBILE_HUD_DENIED_JSON_KEYS = [
${quotedList(privacy.deniedJsonKeys ?? [])}
] as const

export const MOBILE_HUD_DENIED_TEXT_MARKERS = [
${quotedList(privacy.deniedTextMarkers ?? [])}
] as const

export type MobileHudProtocolVersion = typeof MOBILE_HUD_PROTOCOL.protocolVersion
`)

outputs.set(kotlinPath, `package com.claudehud.one.mobile

// ${header}
object MobileHudProtocol {
    const val PROTOCOL_VERSION: Int = ${protocol.protocolVersion}
    const val SCHEMA_VERSION: Int = ${protocol.schemaVersion}
    const val TRUSTED_VIEW_PRIVACY_LEVEL: String = ${JSON.stringify(protocol.privacy.trustedViewPrivacyLevel)}
    const val NOTIFICATION_SENSITIVITY: String = ${JSON.stringify(protocol.privacy.notificationSensitivity)}
    const val MOBILE_EXECUTION_ROLE: String = ${JSON.stringify(protocol.privacy.mobileExecutionRole)}
    const val RAW_TRANSCRIPT_POLICY: String = ${JSON.stringify(protocol.privacy.rawTranscriptPolicy)}
    const val RAW_TOOL_DATA_POLICY: String = ${JSON.stringify(protocol.privacy.rawToolDataPolicy)}
    const val TERMINAL_JUMP: Boolean = ${protocol.displayPolicy.terminalJump}
    const val APPROVAL_ACTIONS: Boolean = ${protocol.displayPolicy.approvalActions}
    const val QUESTION_ACTIONS: Boolean = ${protocol.displayPolicy.questionActions}
    const val TRANSPORT: String = ${JSON.stringify(protocol.security.transport)}
    const val DEVICE_IDENTITY: String = ${JSON.stringify(protocol.security.deviceIdentity)}
    const val INTENT_AUTH: String = ${JSON.stringify(protocol.security.intentAuth)}
    const val DEVICE_ID_IS_CREDENTIAL: Boolean = ${protocol.security.deviceIdIsCredential}

    val DENIED_JSON_KEYS: Set<String> = setOf(
${kotlinStringList(privacy.deniedJsonKeys ?? [])}
    )
}
`)

outputs.set(swiftPath, `// ${header}

public enum MobileHudProtocol {
    public static let protocolVersion: Int = ${protocol.protocolVersion}
    public static let schemaVersion: Int = ${protocol.schemaVersion}
    public static let trustedViewPrivacyLevel: String = ${JSON.stringify(protocol.privacy.trustedViewPrivacyLevel)}
    public static let notificationSensitivity: String = ${JSON.stringify(protocol.privacy.notificationSensitivity)}
    public static let mobileExecutionRole: String = ${JSON.stringify(protocol.privacy.mobileExecutionRole)}
    public static let rawTranscriptPolicy: String = ${JSON.stringify(protocol.privacy.rawTranscriptPolicy)}
    public static let rawToolDataPolicy: String = ${JSON.stringify(protocol.privacy.rawToolDataPolicy)}
    public static let terminalJump: Bool = ${protocol.displayPolicy.terminalJump}
    public static let approvalActions: Bool = ${protocol.displayPolicy.approvalActions}
    public static let questionActions: Bool = ${protocol.displayPolicy.questionActions}
    public static let transport: String = ${JSON.stringify(protocol.security.transport)}
    public static let deviceIdentity: String = ${JSON.stringify(protocol.security.deviceIdentity)}
    public static let intentAuth: String = ${JSON.stringify(protocol.security.intentAuth)}
    public static let deviceIdIsCredential: Bool = ${protocol.security.deviceIdIsCredential}

    public static let deniedJsonKeys: [String] = [
${swiftStringList(privacy.deniedJsonKeys ?? [])}
    ]
}
`)

const normalize = (value) => value.replace(/\r\n/g, '\n')
const failures = []

for (const [path, content] of outputs.entries()) {
  if (mode === 'write') {
    writeFileSync(path, content, 'utf8')
    continue
  }
  let current = ''
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    failures.push(`${path} is missing; run npm run generate:protocol`)
    continue
  }
  if (normalize(current) !== normalize(content)) {
    failures.push(`${path} is out of date; run npm run generate:protocol`)
  }
}

if (failures.length) {
  console.error('Generated Mobile HUD protocol files are stale:')
  failures.forEach((failure) => console.error(`- ${failure}`))
  process.exit(1)
}

console.log(mode === 'write' ? `Generated ${outputs.size} Mobile HUD protocol files.` : `Generated Mobile HUD protocol files are up to date (${outputs.size} files).`)
